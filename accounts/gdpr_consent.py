def user_needs_gdpr_consent(user):
    """True αν ο χρήστης πρέπει να δει το popup συγκατάθεσης."""
    if not user or not getattr(user, 'is_authenticated', False):
        return False
    if not user.can_access_system():
        return False
    accepted_version = getattr(user, 'gdpr_consent_version', 0) or 0
    accepted_at = getattr(user, 'gdpr_consent_accepted_at', None)
    return not accepted_at or accepted_version < GDPR_CONSENT_VERSION
