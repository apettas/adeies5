def privacy_policy_plain_text():
    """Πλήρες κείμενο πολιτικής ως plain text (για καταγραφές / export)."""
    lines = [PRIVACY_POLICY_TITLE, PRIVACY_POLICY_SUBTITLE, '']
    for section in PRIVACY_POLICY_SECTIONS:
        heading = f"{section['number']}. {section['title']}"
        lines.append(heading)
        if section.get('legal_ref'):
            lines.append(section['legal_ref'])
        for p in section.get('paragraphs') or []:
            lines.append(p)
        for b in section.get('bullets') or []:
            lines.append(f'- {b}')
        for p in section.get('paragraphs_after') or []:
            lines.append(p)
        for b in section.get('bullets_after') or []:
            lines.append(f'- {b}')
        if section.get('closing'):
            lines.append(section['closing'])
        lines.append('')
    return '\n'.join(lines).strip()
